#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum NormForm {
    Nfc,
    Nfd,
    Nfkc,
    Nfkd,
}

struct NormData {
    /// (start, end, ccc)
    ccc: Vec<(u32, u32, u8)>,
    /// (code point, offset, len) into `pool`, sorted; canonical single-level mappings
    canon: Vec<(u32, u32, u8)>,
    /// same for compatibility mappings
    compat: Vec<(u32, u32, u8)>,
    pool: Vec<u32>,
    /// ((first << 21) | second, composite), sorted
    compose: Vec<(u64, u32)>,
}

fn norm_data() -> &'static NormData {
    static T: OnceLock<NormData> = OnceLock::new();
    T.get_or_init(|| {
        let mut ccc = Vec::new();
        let mut r = Reader::new(tables::CCC_DATA);
        let mut next = 0u32;
        while !r.done() {
            let s = next + r.uv();
            let e = s + r.uv();
            let v = r.uv() as u8;
            ccc.push((s, e, v));
            next = e + 1;
        }
        let mut pool = Vec::new();
        let mut canon = Vec::new();
        let mut compose = Vec::new();
        let mut r = Reader::new(tables::CANON_DATA);
        let mut c = 0u32;
        while !r.done() {
            c += r.uv();
            let lf = r.uv();
            let len = lf >> 1;
            let off = pool.len() as u32;
            let mut p = c as i64;
            for _ in 0..len {
                p += r.sv();
                pool.push(p as u32);
            }
            if lf & 1 != 0 {
                compose.push((((pool[off as usize] as u64) << 21) | pool[off as usize + 1] as u64, c));
            }
            canon.push((c, off, len as u8));
        }
        let mut compat = Vec::new();
        let mut r = Reader::new(tables::COMPAT_DATA);
        let mut c = 0u32;
        while !r.done() {
            c += r.uv();
            let len = r.uv();
            let off = pool.len() as u32;
            let mut p = c as i64;
            for _ in 0..len {
                p += r.sv();
                pool.push(p as u32);
            }
            compat.push((c, off, len as u8));
        }
        compose.sort_unstable();
        NormData { ccc, canon, compat, pool, compose }
    })
}

const S_BASE: u32 = 0xAC00;
const L_BASE: u32 = 0x1100;
const V_BASE: u32 = 0x1161;
const T_BASE: u32 = 0x11A7;
const L_COUNT: u32 = 19;
const V_COUNT: u32 = 21;
const T_COUNT: u32 = 28;
const N_COUNT: u32 = V_COUNT * T_COUNT;
const S_COUNT: u32 = L_COUNT * N_COUNT;

/// Canonical combining class (as implemented by the original).
pub fn canonical_combining_class(c: u32) -> u8 {
    if c < 0x300 {
        return 0;
    }
    let t = &norm_data().ccc;
    let idx = t.partition_point(|&(s, _, _)| s <= c);
    if idx > 0 && c <= t[idx - 1].1 {
        t[idx - 1].2
    } else {
        0
    }
}

fn mapping(t: &[(u32, u32, u8)], pool: &'static [u32], c: u32) -> Option<&'static [u32]> {
    let i = t.binary_search_by(|&(k, _, _)| k.cmp(&c)).ok()?;
    let (_, off, len) = t[i];
    Some(&pool[off as usize..off as usize + len as usize])
}

fn decompose_into(c: u32, compat: bool, out: &mut Vec<u32>) {
    if (S_BASE..S_BASE + S_COUNT).contains(&c) {
        let s = c - S_BASE;
        out.push(L_BASE + s / N_COUNT);
        out.push(V_BASE + (s % N_COUNT) / T_COUNT);
        let t = s % T_COUNT;
        if t != 0 {
            out.push(T_BASE + t);
        }
        return;
    }
    if c < 0xA0 {
        out.push(c);
        return;
    }
    let d = norm_data();
    if let Some(m) = mapping(&d.canon, &d.pool, c) {
        for &x in m {
            decompose_into(x, compat, out);
        }
        return;
    }
    if compat {
        if let Some(m) = mapping(&d.compat, &d.pool, c) {
            for &x in m {
                decompose_into(x, compat, out);
            }
            return;
        }
    }
    out.push(c);
}

fn compose_pair(a: u32, b: u32) -> Option<u32> {
    // Hangul
    if (L_BASE..L_BASE + L_COUNT).contains(&a) && (V_BASE..V_BASE + V_COUNT).contains(&b) {
        return Some(S_BASE + ((a - L_BASE) * V_COUNT + (b - V_BASE)) * T_COUNT);
    }
    if (S_BASE..S_BASE + S_COUNT).contains(&a)
        && (a - S_BASE) % T_COUNT == 0
        && (T_BASE + 1..T_BASE + T_COUNT).contains(&b)
    {
        return Some(a + (b - T_BASE));
    }
    let key = ((a as u64) << 21) | b as u64;
    let t = &norm_data().compose;
    t.binary_search_by(|&(k, _)| k.cmp(&key)).ok().map(|i| t[i].1)
}

/// String.prototype.normalize (lone surrogates pass through unchanged). For an invalid form the
/// original throws `RangeError: The normalization form should be one of NFC, NFD, NFKC, NFKD`
/// (no trailing period); `normalize()` / `normalize(undefined)` mean NFC.
pub fn normalize(s: &[u16], form: NormForm) -> Vec<u16> {
    // quick checks: code units below these limits are unaffected by the respective forms
    let limit = match form {
        NormForm::Nfc => 0x300,
        NormForm::Nfd => 0xC0,
        NormForm::Nfkc | NormForm::Nfkd => 0xA0,
    };
    if s.iter().all(|&u| (u as u32) < limit) {
        return s.to_vec();
    }
    let compat = matches!(form, NormForm::Nfkc | NormForm::Nfkd);
    // decompose
    let mut cps: Vec<u32> = Vec::with_capacity(s.len() + 8);
    let mut i = 0;
    while i < s.len() {
        let (c, n) = cp_at(s, i);
        i += n;
        if (0xD800..0xE000).contains(&c) {
            cps.push(c);
        } else {
            decompose_into(c, compat, &mut cps);
        }
    }
    // canonical ordering: stable sort of each run of non-starters by ccc
    let classes: Vec<u8> = cps.iter().map(|&c| canonical_combining_class(c)).collect();
    let mut k = 0;
    while k < cps.len() {
        if classes[k] == 0 {
            k += 1;
            continue;
        }
        let start = k;
        while k < cps.len() && classes[k] != 0 {
            k += 1;
        }
        if k - start > 1 {
            let mut run: Vec<(u8, u32)> = (start..k).map(|j| (classes[j], cps[j])).collect();
            run.sort_by_key(|&(cc, _)| cc); // stable
            for (j, (_, c)) in run.into_iter().enumerate() {
                cps[start + j] = c;
            }
        }
    }
    if matches!(form, NormForm::Nfc | NormForm::Nfkc) {
        cps = compose(&cps);
    }
    let mut out = Vec::with_capacity(cps.len());
    for c in cps {
        push_cp(&mut out, c);
    }
    out
}

fn compose(cps: &[u32]) -> Vec<u32> {
    let mut out: Vec<u32> = Vec::with_capacity(cps.len());
    let mut starter: Option<usize> = None;
    let mut last_cc: u8 = 0;
    for &c in cps {
        let cc = canonical_combining_class(c);
        if let Some(sp) = starter {
            let adjacent = out.len() == sp + 1;
            if adjacent || (last_cc != 0 && last_cc < cc) {
                if let Some(comp) = compose_pair(out[sp], c) {
                    out[sp] = comp;
                    continue;
                }
            }
        }
        if cc == 0 {
            starter = Some(out.len());
        }
        last_cc = cc;
        out.push(c);
    }
    out
}

