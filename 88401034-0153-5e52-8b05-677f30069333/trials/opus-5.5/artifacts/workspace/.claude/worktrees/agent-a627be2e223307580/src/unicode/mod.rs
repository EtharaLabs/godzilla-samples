struct ScxData {
    /// (start, end, set index), sorted
    runs: Vec<(u32, u32, u16)>,
    sets: Vec<Vec<u8>>,
}

fn scx_data() -> &'static ScxData {
    static T: OnceLock<ScxData> = OnceLock::new();
    T.get_or_init(|| {
        let mut sets = Vec::new();
        let mut r = Reader::new(tables::SCX_SETS);
        while !r.done() {
            let n = r.uv();
            sets.push((0..n).map(|_| r.uv() as u8).collect::<Vec<u8>>());
        }
        let mut runs = Vec::new();
        let mut r = Reader::new(tables::SCX_RUNS);
        let mut next = 0u32;
        while !r.done() {
            let s = next + r.uv();
            let e = s + r.uv();
            let k = r.uv() as u16;
            runs.push((s, e, k));
            next = e + 1;
        }
        ScxData { runs, sets }
    })
}

/// Script value lookup. The original matches script values loosely: ASCII case-insensitive and
/// ignoring underscores (`sc=latin`, `sc=OLD_ITALIC`, `sc=olditalic` are all accepted), while
/// General_Category values and binary property names are matched exactly.
fn script_id(name: &str) -> Option<u8> {
    let key: String = name.chars().filter(|&c| c != '_').map(|c| c.to_ascii_lowercase()).collect();
    tables::SCRIPT_NAMES
        .binary_search_by(|&(n, _)| n.cmp(key.as_str()))
        .ok()
        .map(|i| tables::SCRIPT_NAMES[i].1)
}

/// Script property value (long name) of a code point, e.g. "Latin", "Common", "Unknown".
pub fn script(c: u32) -> &'static str {
    if c > 0x10FFFF {
        return "Unknown";
    }
    tables::SCRIPT_LONG[partition_lookup(sc_table(), c) as usize]
}

/// Script_Extensions of a code point (long names).
pub fn script_extensions(c: u32) -> Vec<&'static str> {
    let d = scx_data();
    let idx = d.runs.partition_point(|&(s, _, _)| s <= c);
    if idx > 0 && c <= d.runs[idx - 1].1 {
        return d.sets[d.runs[idx - 1].2 as usize]
            .iter()
            .map(|&i| tables::SCRIPT_LONG[i as usize])
            .collect();
    }
    vec![script(c)]
}

fn script_ranges(id: u8) -> Vec<(u32, u32)> {
    partition_ranges(sc_table(), |s| s == id)
}

fn scx_ranges(id: u8) -> Vec<(u32, u32)> {
    let d = scx_data();
    let base = script_ranges(id);
    let all_runs: Vec<(u32, u32)> = normalize_ranges(d.runs.iter().map(|&(s, e, _)| (s, e)).collect());
    let mut v = subtract_ranges(&base, &all_runs);
    for &(s, e, k) in &d.runs {
        if d.sets[k as usize].contains(&id) {
            v.push((s, e));
        }
    }
    normalize_ranges(v)
}

