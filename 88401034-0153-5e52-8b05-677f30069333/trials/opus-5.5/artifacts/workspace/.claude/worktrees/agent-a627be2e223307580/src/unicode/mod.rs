//! Unicode utilities for the lumen runtime (std only).
//!
//! The data reproduces what the original runtime implements, which is Unicode 17.0:
//! property tables (General_Category, Script, Script_Extensions, the 53 ECMAScript binary
//! properties, properties of strings), case folding classes and normalization data were probed
//! from the original and cross-checked against UCD 15.0 (python `unicodedata`, perl, and the
//! `regenerate-unicode-properties` package); full case mappings come from Rust std (Unicode 17.0),
//! which matches the original's `toUpperCase`/`toLowerCase` exactly for every code point.
//! The compact tables live in `tables.rs` (generated by `/tmp/unicode_dev/gen/gen_tables.py`).
//!
//! Quirks of the original reproduced here:
//! * `\p{Basic_Emoji}` contains the 26 regional indicators U+1F1E6..U+1F1FF as single code points
//!   and the 12 keycap bases followed by U+FE0F (`#\u{FE0F}` ...) as strings, and
//!   `\p{RGI_Emoji_Modifier_Sequence}` contains U+1F46A + skin tone; `\p{RGI_Emoji}` contains none
//!   of these (it is not exactly the union of the other six properties of strings).
//! * `WSpace` is not accepted as an alias of `White_Space` (only `space` is, per ECMA-262);
//!   `Katakana_Or_Hiragana`/`Hrkt` are not accepted script values. Binary property names and
//!   General_Category values are case-sensitive, but Script/Script_Extensions values are matched
//!   loosely (ASCII case-insensitive, underscores ignored: `\p{sc=latin}`, `\p{sc=OLD_ITALIC}`).
//! * Canonical combining classes are those of UCD 15.0 plus only twelve new non-zero classes
//!   (U+0897, U+10D69..U+10D6D, U+113CE..U+113D0, U+1612F, U+1E5EE, U+1E5EF); other marks added
//!   in Unicode 16.0/17.0 behave as ccc=0 in `normalize`.
//! * Final sigma uses the ICU rule: case-ignorable characters are skipped even when they are
//!   also cased, lone surrogates stop the scan.
//! * `normalize` passes lone surrogates through unchanged and treats them as starters (ccc 0)
//!   that never compose.
#![allow(dead_code)]

