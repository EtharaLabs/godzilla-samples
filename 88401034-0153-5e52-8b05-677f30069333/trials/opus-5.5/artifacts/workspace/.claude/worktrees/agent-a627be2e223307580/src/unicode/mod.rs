/// Reader for the base-64 varint encoding used by `tables.rs`: each byte in 0x30..=0x6F holds
/// five data bits (least significant group first); bit 5 means "more bytes follow".
struct Reader<'a> {
    s: &'a [u8],
    i: usize,
}

impl<'a> Reader<'a> {
    fn new(s: &'a str) -> Self {
        Reader { s: s.as_bytes(), i: 0 }
    }
    fn done(&self) -> bool {
        self.i >= self.s.len()
    }
    fn uv(&mut self) -> u32 {
        let mut v: u32 = 0;
        let mut shift = 0;
        loop {
            let b = (self.s[self.i] - 0x30) as u32;
            self.i += 1;
            v |= (b & 31) << shift;
            if b & 32 == 0 {
                return v;
            }
            shift += 5;
        }
    }
    fn sv(&mut self) -> i64 {
        let u = self.uv() as i64;
        if u & 1 == 0 {
            u >> 1
        } else {
            -((u + 1) >> 1)
        }
    }
}

fn decode_ranges(s: &str) -> Vec<(u32, u32)> {
    let mut r = Reader::new(s);
    let mut out = Vec::new();
    let mut next: u32 = 0;
    while !r.done() {
        let start = next + r.uv();
        let end = start + r.uv();
        out.push((start, end));
        next = end + 1;
    }
    out
}

fn in_ranges(ranges: &[(u32, u32)], c: u32) -> bool {
    // binary search for the last range with start <= c
    let idx = ranges.partition_point(|&(s, _)| s <= c);
    idx > 0 && c <= ranges[idx - 1].1
}

/// Sort and merge (overlapping or adjacent) ranges.
fn normalize_ranges(mut v: Vec<(u32, u32)>) -> Vec<(u32, u32)> {
    v.sort_unstable();
    let mut out: Vec<(u32, u32)> = Vec::with_capacity(v.len());
    for (a, b) in v {
        if let Some(last) = out.last_mut() {
            if a <= last.1.saturating_add(1) {
                if b > last.1 {
                    last.1 = b;
                }
                continue;
            }
        }
        out.push((a, b));
    }
    out
}

/// `a` minus `b` (both sorted, non-overlapping).
fn subtract_ranges(a: &[(u32, u32)], b: &[(u32, u32)]) -> Vec<(u32, u32)> {
    let mut out = Vec::new();
    let mut j = 0;
    for &(s, e) in a {
        let mut cur = s;
        while j < b.len() && b[j].1 < cur {
            j += 1;
        }
        let mut k = j;
        let mut alive = true;
        while k < b.len() && b[k].0 <= e {
            if b[k].0 > cur {
                out.push((cur, b[k].0 - 1));
            }
            if b[k].1 >= e {
                alive = false;
                break;
            }
            cur = b[k].1 + 1;
            k += 1;
        }
        if alive && cur <= e {
            out.push((cur, e));
        }
    }
    out
}

