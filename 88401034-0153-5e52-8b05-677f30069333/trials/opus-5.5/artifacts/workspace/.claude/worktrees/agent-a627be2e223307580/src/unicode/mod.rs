fn decode_pairs(s: &str) -> Vec<(u32, u32)> {
    let mut r = Reader::new(s);
    let mut out = Vec::new();
    let mut c = 0u32;
    while !r.done() {
        c += r.uv();
        let d = r.sv();
        out.push((c, (c as i64 + d) as u32));
    }
    out
}

