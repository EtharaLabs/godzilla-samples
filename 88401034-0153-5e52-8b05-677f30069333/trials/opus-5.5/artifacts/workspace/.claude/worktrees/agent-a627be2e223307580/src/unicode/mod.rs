fn pair_lookup(t: &[(u32, u32)], c: u32) -> u32 {
    match t.binary_search_by(|&(k, _)| k.cmp(&c)) {
        Ok(i) => t[i].1,
        Err(_) => c,
    }
}

/// Simple case folding (CaseFolding.txt status C+S) = Canonicalize for u/v-mode /i.
pub fn simple_case_fold(c: u32) -> u32 {
    if c < 0x80 {
        return if (b'A' as u32..=b'Z' as u32).contains(&c) { c + 32 } else { c };
    }
    pair_lookup(simple_case_fold_table(), c)
}

/// Non-unicode /i Canonicalize of a code unit: u = full toUppercase(ch); if u is not a single
/// code unit return ch; if ch >= 128 && u < 128 return ch; else u. For c > 0xFFFF returns c.
pub fn legacy_canonicalize(c: u32) -> u32 {
    if c < 0x80 {
        return if (b'a' as u32..=b'z' as u32).contains(&c) { c - 32 } else { c };
    }
    if c > 0xFFFF {
        return c;
    }
    pair_lookup(legacy_canonicalize_table(), c)
}

struct Classes {
    /// (code point, offset into pool, len) sorted by code point; only for non-trivial classes
    index: Vec<(u32, u32, u8)>,
    pool: Vec<u32>,
}

fn make_classes(t: &[(u32, u32)]) -> Classes {
    use std::collections::BTreeMap;
    let mut groups: BTreeMap<u32, Vec<u32>> = BTreeMap::new();
    for &(c, f) in t {
        groups.entry(f).or_default().push(c);
    }
    let mut pool = Vec::new();
    let mut index = Vec::new();
    for (rep, mut members) in groups {
        members.push(rep);
        members.sort_unstable();
        members.dedup();
        let off = pool.len() as u32;
        let len = members.len() as u8;
        for &m in &members {
            index.push((m, off, len));
        }
        pool.extend(members);
    }
    index.sort_unstable();
    Classes { index, pool }
}

fn class_lookup(cl: &'static Classes, c: u32) -> Option<&'static [u32]> {
    let i = cl.index.binary_search_by(|&(k, _, _)| k.cmp(&c)).ok()?;
    let (_, off, len) = cl.index[i];
    Some(&cl.pool[off as usize..off as usize + len as usize])
}

/// All code points with the same simple case folding as `c` (sorted, including `c`), or None
/// if `c` is alone in its class.
pub fn simple_case_fold_class(c: u32) -> Option<&'static [u32]> {
    static T: OnceLock<Classes> = OnceLock::new();
    class_lookup(T.get_or_init(|| make_classes(simple_case_fold_table())), c)
}

/// All code units with the same legacy canonicalization as `c` (sorted, including `c`), or None
/// if `c` is alone in its class.
pub fn legacy_canonicalize_class(c: u32) -> Option<&'static [u32]> {
    static T: OnceLock<Classes> = OnceLock::new();
    class_lookup(T.get_or_init(|| make_classes(legacy_canonicalize_table())), c)
}

