impl GeneralCategory {
    /// Two-letter short name (e.g. "Lu").
    pub fn short_name(self) -> &'static str {
        tables::GC_ORDER[self as usize]
    }
}

/// Partition of the code space: (start, category index); sorted, first start is 0.
fn gc_table() -> &'static [(u32, u8)] {
    static T: OnceLock<Vec<(u32, u8)>> = OnceLock::new();
    T.get_or_init(|| {
        let mut r = Reader::new(tables::GC_DATA);
        let mut out = Vec::with_capacity(4200);
        let mut pos = 0u32;
        while !r.done() {
            pos += r.uv();
            let g = r.uv() as u8;
            out.push((pos, g));
        }
        out
    })
}

fn partition_lookup(t: &[(u32, u8)], c: u32) -> u8 {
    let idx = t.partition_point(|&(s, _)| s <= c);
    t[idx - 1].1
}

pub fn general_category(c: u32) -> GeneralCategory {
    if c > 0x10FFFF {
        return GeneralCategory::Cn;
    }
    GC_ALL[partition_lookup(gc_table(), c) as usize]
}

/// Ranges of a partition table whose value satisfies `pred`.
fn partition_ranges(t: &[(u32, u8)], pred: impl Fn(u8) -> bool) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = Vec::new();
    for (i, &(s, v)) in t.iter().enumerate() {
        if !pred(v) {
            continue;
        }
        let e = if i + 1 < t.len() { t[i + 1].0 - 1 } else { 0x10FFFF };
        if let Some(last) = out.last_mut() {
            if last.1 + 1 == s {
                last.1 = e;
                continue;
            }
        }
        out.push((s, e));
    }
    out
}

fn gc_mask(name: &str) -> Option<u32> {
    tables::GC_NAMES
        .binary_search_by(|&(n, _)| n.cmp(name))
        .ok()
        .map(|i| tables::GC_NAMES[i].1)
}

fn gc_ranges(mask: u32) -> Vec<(u32, u32)> {
    partition_ranges(gc_table(), |g| mask & (1 << g) != 0)
}

