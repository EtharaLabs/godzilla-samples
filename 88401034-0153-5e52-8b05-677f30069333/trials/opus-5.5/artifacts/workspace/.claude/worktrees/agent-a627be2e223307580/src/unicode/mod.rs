type StringProp = (Vec<(u32, u32)>, Vec<Vec<u32>>);

fn string_props() -> &'static Vec<StringProp> {
    static T: OnceLock<Vec<StringProp>> = OnceLock::new();
    T.get_or_init(|| {
        let mut dict = Vec::new();
        for (a, b) in decode_ranges(tables::STR_DICT) {
            dict.extend(a..=b);
        }
        let decode_strings = |s: &str| -> Vec<Vec<u32>> {
            let mut r = Reader::new(s);
            let mut v = Vec::new();
            if !r.done() {
                let n = r.uv();
                for _ in 0..n {
                    let len = r.uv();
                    v.push((0..len).map(|_| dict[r.uv() as usize]).collect::<Vec<u32>>());
                }
            }
            v
        };
        let mut out: Vec<StringProp> = Vec::new();
        for &(name, singles, strings) in tables::STRING_PROPS.iter() {
            let ranges = decode_ranges(singles);
            let mut v = decode_strings(strings);
            if name == "RGI_Emoji" {
                let excluded = decode_strings(tables::RGI_EMOJI_EXCLUDED);
                for (_, other) in &out {
                    v.extend(other.iter().filter(|s| !excluded.contains(s)).cloned());
                }
                v.sort_unstable();
                v.dedup();
            }
            out.push((ranges, v));
        }
        out
    })
}

/// v-mode properties of strings (Basic_Emoji, Emoji_Keycap_Sequence, RGI_Emoji_Modifier_Sequence,
/// RGI_Emoji_Flag_Sequence, RGI_Emoji_Tag_Sequence, RGI_Emoji_ZWJ_Sequence, RGI_Emoji):
/// (single code points as merged ranges, strings of >= 2 code points, sorted); None otherwise.
pub fn string_property(name: &str) -> Option<(Vec<(u32, u32)>, Vec<Vec<u32>>)> {
    string_property_ref(name).map(|(r, s)| (r.to_vec(), s.to_vec()))
}

/// Same as `string_property` without copying the (cached) data.
pub fn string_property_ref(name: &str) -> Option<(&'static [(u32, u32)], &'static [Vec<u32>])> {
    let idx = tables::STRING_PROPS.iter().position(|&(n, _, _)| n == name)?;
    let (r, s) = &string_props()[idx];
    Some((r.as_slice(), s.as_slice()))
}

