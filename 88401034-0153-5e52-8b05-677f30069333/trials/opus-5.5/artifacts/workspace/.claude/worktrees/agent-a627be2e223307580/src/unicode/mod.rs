fn binary_tables() -> &'static Vec<OnceLock<Vec<(u32, u32)>>> {
    static T: OnceLock<Vec<OnceLock<Vec<(u32, u32)>>>> = OnceLock::new();
    T.get_or_init(|| (0..tables::BINARY_PROPS.len()).map(|_| OnceLock::new()).collect())
}

/// Decoded (cached) ranges of a stored binary property, by canonical name.
fn stored_binary(canonical: &str) -> Option<&'static [(u32, u32)]> {
    let idx = tables::BINARY_PROPS.iter().position(|&(n, _)| n == canonical)?;
    let cell = &binary_tables()[idx];
    Some(cell.get_or_init(|| decode_ranges(tables::BINARY_PROPS[idx].1)).as_slice())
}

fn binary_canonical(name: &str) -> Option<&'static str> {
    tables::BINARY_NAMES
        .binary_search_by(|&(n, _)| n.cmp(name))
        .ok()
        .map(|i| tables::BINARY_NAMES[i].1)
}

fn binary_ranges(name: &str) -> Option<Vec<(u32, u32)>> {
    let canonical = binary_canonical(name)?;
    match canonical {
        "Any" => Some(vec![(0, 0x10FFFF)]),
        "ASCII" => Some(vec![(0, 0x7F)]),
        "Assigned" => Some(gc_ranges(!(1u32 << GeneralCategory::Cn as u32) & ((1 << 30) - 1))),
        _ => stored_binary(canonical).map(|r| r.to_vec()),
    }
}

/// Fast membership test for a stored binary property (canonical name).
fn has_binary(canonical: &'static str, c: u32) -> bool {
    match stored_binary(canonical) {
        Some(r) => in_ranges(r, c),
        None => false,
    }
}

/// `\p{name}` / `\p{name=value}` character properties, names exactly as written in the pattern
/// (case-sensitive, ECMA-262 names and aliases as accepted by the original). Returns sorted,
/// non-overlapping, non-adjacent inclusive ranges, or None if the original rejects the property.
/// Properties of strings are excluded (see `string_property`).
pub fn property_ranges(name: &str, value: Option<&str>) -> Option<Vec<(u32, u32)>> {
    match value {
        None => {
            if let Some(m) = gc_mask(name) {
                return Some(gc_ranges(m));
            }
            binary_ranges(name)
        }
        Some(v) => match name {
            "General_Category" | "gc" => gc_mask(v).map(gc_ranges),
            "Script" | "sc" => script_id(v).map(script_ranges),
            "Script_Extensions" | "scx" => script_id(v).map(scx_ranges),
            _ => None,
        },
    }
}

/// Membership test for the same names as `property_ranges` (slower than caching the ranges).
pub fn has_property(name: &str, value: Option<&str>, c: u32) -> Option<bool> {
    property_ranges(name, value).map(|r| in_ranges(&r, c))
}

pub fn is_id_start(c: u32) -> bool {
    if c < 0x80 {
        return (c as u8).is_ascii_alphabetic();
    }
    static T: OnceLock<&'static [(u32, u32)]> = OnceLock::new();
    in_ranges(T.get_or_init(|| stored_binary("ID_Start").unwrap()), c)
}

pub fn is_id_continue(c: u32) -> bool {
    if c < 0x80 {
        return (c as u8).is_ascii_alphanumeric() || c == b'_' as u32;
    }
    static T: OnceLock<&'static [(u32, u32)]> = OnceLock::new();
    in_ranges(T.get_or_init(|| stored_binary("ID_Continue").unwrap()), c)
}

/// ID_Start plus '$' and '_' (ECMAScript IdentifierStartChar).
pub fn is_js_id_start(c: u32) -> bool {
    c == '$' as u32 || c == '_' as u32 || is_id_start(c)
}

/// ID_Continue plus '$', ZWNJ and ZWJ (ECMAScript IdentifierPartChar).
pub fn is_js_id_continue(c: u32) -> bool {
    c == '$' as u32 || c == 0x200C || c == 0x200D || is_id_continue(c)
}

/// ECMAScript WhiteSpace: TAB VT FF SP NBSP ZWNBSP and General_Category=Zs.
pub fn is_js_whitespace(c: u32) -> bool {
    match c {
        0x09 | 0x0B | 0x0C | 0x20 | 0xA0 | 0xFEFF => true,
        _ if c < 0x1680 => false,
        _ => tables::ZS.iter().any(|&(a, b)| a <= c && c <= b),
    }
}

/// ECMAScript LineTerminator: LF CR LS PS.
pub fn is_line_terminator(c: u32) -> bool {
    matches!(c, 0x0A | 0x0D | 0x2028 | 0x2029)
}

/// Unicode `Cased` property.
pub fn is_cased(c: u32) -> bool {
    if c < 0x80 {
        return (c as u8).is_ascii_alphabetic();
    }
    static T: OnceLock<&'static [(u32, u32)]> = OnceLock::new();
    in_ranges(T.get_or_init(|| stored_binary("Cased").unwrap()), c)
}

/// Unicode `Case_Ignorable` property.
pub fn is_case_ignorable(c: u32) -> bool {
    static T: OnceLock<&'static [(u32, u32)]> = OnceLock::new();
    in_ranges(T.get_or_init(|| stored_binary("Case_Ignorable").unwrap()), c)
}

