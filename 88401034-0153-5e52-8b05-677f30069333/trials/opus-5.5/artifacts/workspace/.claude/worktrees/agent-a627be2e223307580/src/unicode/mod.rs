/// Result of a full case mapping: up to 3 code points. Iterates over them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct CaseMapping {
    buf: [u32; 3],
    len: u8,
    pos: u8,
}

impl CaseMapping {
    fn one(c: u32) -> Self {
        CaseMapping { buf: [c, 0, 0], len: 1, pos: 0 }
    }
    fn from_iter(it: impl Iterator<Item = char>) -> Self {
        let mut m = CaseMapping { buf: [0; 3], len: 0, pos: 0 };
        for ch in it {
            m.buf[m.len as usize] = ch as u32;
            m.len += 1;
        }
        m
    }
    /// The mapped code points.
    pub fn as_slice(&self) -> &[u32] {
        &self.buf[self.pos as usize..self.len as usize]
    }
    /// True if the mapping is the single code point `c`.
    pub fn is_identity(&self, c: u32) -> bool {
        self.len == 1 && self.buf[0] == c
    }
}

impl Iterator for CaseMapping {
    type Item = u32;
    fn next(&mut self) -> Option<u32> {
        if self.pos < self.len {
            self.pos += 1;
            Some(self.buf[self.pos as usize - 1])
        } else {
            None
        }
    }
    fn size_hint(&self) -> (usize, Option<usize>) {
        let n = (self.len - self.pos) as usize;
        (n, Some(n))
    }
}

impl ExactSizeIterator for CaseMapping {}

/// Full (unconditional, language-independent) uppercase mapping of a code point.
pub fn to_upper_full(c: u32) -> CaseMapping {
    match char::from_u32(c) {
        Some(ch) if ch.is_ascii() => CaseMapping::one(ch.to_ascii_uppercase() as u32),
        Some(ch) => CaseMapping::from_iter(ch.to_uppercase()),
        None => CaseMapping::one(c),
    }
}

/// Full (unconditional, language-independent) lowercase mapping of a code point
/// (U+03A3 maps to U+03C3; the final-sigma rule is applied by `str_to_lower`).
pub fn to_lower_full(c: u32) -> CaseMapping {
    match char::from_u32(c) {
        Some(ch) if ch.is_ascii() => CaseMapping::one(ch.to_ascii_lowercase() as u32),
        Some(ch) => CaseMapping::from_iter(ch.to_lowercase()),
        None => CaseMapping::one(c),
    }
}

/// Decode the code point at `i` (lone surrogates are returned as themselves); returns (cp, len).
#[inline]
fn cp_at(s: &[u16], i: usize) -> (u32, usize) {
    let u = s[i] as u32;
    if (0xD800..0xDC00).contains(&u) && i + 1 < s.len() {
        let l = s[i + 1] as u32;
        if (0xDC00..0xE000).contains(&l) {
            return (0x10000 + ((u - 0xD800) << 10) + (l - 0xDC00), 2);
        }
    }
    (u, 1)
}

/// Decode the code point ending just before `i`; returns (cp, len).
#[inline]
fn cp_before(s: &[u16], i: usize) -> (u32, usize) {
    let u = s[i - 1] as u32;
    if (0xDC00..0xE000).contains(&u) && i >= 2 {
        let h = s[i - 2] as u32;
        if (0xD800..0xDC00).contains(&h) {
            return (0x10000 + ((h - 0xD800) << 10) + (u - 0xDC00), 2);
        }
    }
    (u, 1)
}

#[inline]
fn push_cp(out: &mut Vec<u16>, c: u32) {
    if c < 0x10000 {
        out.push(c as u16);
    } else {
        let c = c - 0x10000;
        out.push((0xD800 + (c >> 10)) as u16);
        out.push((0xDC00 + (c & 0x3FF)) as u16);
    }
}

/// String.prototype.toUpperCase (lone surrogates unchanged).
pub fn str_to_upper(s: &[u16]) -> Vec<u16> {
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while i < s.len() {
        let u = s[i];
        if u < 0x80 {
            out.push((u as u8).to_ascii_uppercase() as u16);
            i += 1;
            continue;
        }
        let (c, n) = cp_at(s, i);
        for m in to_upper_full(c) {
            push_cp(&mut out, m);
        }
        i += n;
    }
    out
}

/// Final_Sigma condition for the capital sigma at code unit index `i` (ICU semantics).
fn is_final_sigma(s: &[u16], i: usize) -> bool {
    // preceded by a cased letter, skipping case-ignorable characters
    let mut j = i;
    let mut before = false;
    while j > 0 {
        let (c, n) = cp_before(s, j);
        j -= n;
        if is_case_ignorable(c) {
            continue;
        }
        before = is_cased(c);
        break;
    }
    if !before {
        return false;
    }
    // not followed by a cased letter, skipping case-ignorable characters
    let mut j = i + 1;
    while j < s.len() {
        let (c, n) = cp_at(s, j);
        j += n;
        if is_case_ignorable(c) {
            continue;
        }
        return !is_cased(c);
    }
    true
}

/// String.prototype.toLowerCase incl. the final sigma rule (lone surrogates unchanged).
pub fn str_to_lower(s: &[u16]) -> Vec<u16> {
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while i < s.len() {
        let u = s[i];
        if u < 0x80 {
            out.push((u as u8).to_ascii_lowercase() as u16);
            i += 1;
            continue;
        }
        if u == 0x3A3 {
            out.push(if is_final_sigma(s, i) { 0x3C2 } else { 0x3C3 });
            i += 1;
            continue;
        }
        let (c, n) = cp_at(s, i);
        for m in to_lower_full(c) {
            push_cp(&mut out, m);
        }
        i += n;
    }
    out
}

