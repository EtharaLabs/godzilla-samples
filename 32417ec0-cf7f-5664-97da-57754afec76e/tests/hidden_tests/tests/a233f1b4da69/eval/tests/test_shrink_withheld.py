def test_build_excluded_file_of_its_own_package(run, workdir):
    """CATCHES: a fix that renames a name a build-excluded file of the same package writes (it would keep the old
    name), or a field or method such a file may use without naming (an io.Closer it asks for)."""
    out = shrink_fix(run, workdir, {
        "internal/x/x.go": """package x

var WinRef = 1

func Unnamed() {}

type Own struct {
	F int
}

func (Own) Close() error { return nil }

func newOwn() Own { return Own{} }

var _ = Own{}.F
""",
        "internal/x/x_never.go": '//go:build never\n\npackage x\n\nimport "io"\n\nvar _ = WinRef\n\nvar _ io.Closer = newOwn()\n',
    }, ("internal/x/x.go",))
    assert_golden(out, __file__, "excluded_own")


def test_build_excluded_file_reaches_through_a_compiled_sibling(run, workdir):
    """CATCHES: a shrink that only looks at what a build-excluded file imports: one that imports nothing may still
    read a value through a variable its compiled sibling declares, so fields and methods lose their fix."""
    out = shrink_fix(run, workdir, {
        "internal/s/s.go": """package s

type S struct {
	Field int
}

func (S) Method() string { return "" }

func New() S { return S{} }

func Plain() {}
""",
        "internal/t/t.go": 'package t\n\nimport "example.com/withheld/internal/s"\n\nvar v = s.New()\n',
        "internal/t/t_never.go": "//go:build never\n\npackage t\n\nfunc w() string { return v.Method() + string(rune(v.Field)) }\n",
    }, ("internal/s/s.go",))
    assert_golden(out, __file__, "excluded_sibling")


def test_build_excluded_file_importing_the_package(run, workdir):
    """CATCHES: a shrink that fixes a field, method or embedded type a build-excluded importer may reach
    (keyed and unkeyed literals, interface satisfaction, conversions, embedded selections), or that withholds the
    fix of a package-level name such a file never writes."""
    out = shrink_fix(run, workdir, {
        "internal/y/y.go": """package y

func Unnamed() {}

type Runner struct{}

func (Runner) Run() {}

func NewRunner() Runner { return Runner{} }

type Converted struct {
	Flag int
}

type Holder struct{ Embedded }

type Embedded struct{}

func NewHolder() Holder { return Holder{} }

type Keyed struct {
	Flag  int
	Other int
}

type Filled struct {
	A int
	B string
}

type InSlice struct {
	C int
}

type InMap struct {
	D int
}
""",
        "internal/v/v.go": "package v\n",
        "internal/v/v_never.go": """//go:build never

package v

import "example.com/withheld/internal/y"

type runner interface{ Run() }

var (
	_ = y.Keyed{Flag: 1}
	_ = y.Filled{1, "x"}
	_ = []y.InSlice{{1}}
	_ = map[string]*y.InMap{"k": {1}}
	_ = []*y.InSlice{&y.InSlice{2}}

	_ runner = y.NewRunner()
	_        = y.Converted(struct{ Flag int }{1})
	_        = y.NewHolder().Embedded
)
""",
    }, ("internal/y/y.go",))
    assert_golden(out, __file__, "excluded_importer")
