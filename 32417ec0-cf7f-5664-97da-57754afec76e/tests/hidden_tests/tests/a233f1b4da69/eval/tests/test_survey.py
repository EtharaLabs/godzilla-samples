"""declscope survey: the checks in force, the findings per rule, and one row per package, as Markdown or JSON."""

import pytest

from conftest import assert_golden, gomod, transcript, write_files


@pytest.fixture
def workdir(fixed_workdir):
    """Survey tables hold absolute paths, so their padding needs a path of fixed length."""
    return fixed_workdir

STRICT = "rules:\n  naming:\n    qualify: ondemand\n    exported: true\n"

# A package with every kind of crossing: reported (helper), declared shared (shared), baselined (legacy), into the
# core (open), and a qualify finding (helper, legacy) beside an ignored one (quiet).
RICH = {
    "go.mod": gomod("example.com/m"),
    ".declscope.yaml": STRICT,
    "app/user.go": """package app

func helper() int { return 1 }

//declscope:shared
func userShared() int { return 2 }

func legacy() int { return 3 }

//declscope:ignore qualify
func quiet() int { return 4 }

func userOwn() int { return quiet() }

var _ = userOwn
""",
    "app/order.go": "package app\n\nfunc orderRun() int { return helper() + userShared() + legacy() + open() }\n\nvar _ = orderRun\n",
    "app/core.go": "//declscope:core\n\npackage app\n\nfunc open() int { return 0 }\n",
    "app/.declscope-baseline.yaml": "packages:\n  example.com/m/app:\n    boundary:\n      user:\n        - legacy\n    qualify:\n      user:\n        - legacy\n",
    "allcore/a.go": "//declscope:core\n\npackage allcore\n\nfunc a() int { return b() }\n",
    "allcore/b.go": "//declscope:core\n\npackage allcore\n\nfunc b() int { return 1 }\n\nvar _ = a\n",
    "gen/gen.go": "// Code generated by hand. DO NOT EDIT.\n\npackage gen\n\nfunc g() {}\n",
    "off/.declscope.yaml": "rules:\n  boundary: off\n  surplus: off\n  unused: off\n  naming:\n    qualify: never\n",
    "off/a.go": "package off\n\nfunc a() int { return 1 }\n",
    "off/b.go": "package off\n\nvar _ = a()\n",
}


def survey(run, workdir, files, *args):
    write_files(workdir, files)
    return transcript(run(["survey", *args]), workdir)


def test_help(run, workdir):
    """CATCHES: a survey -h that omits -allow-errors, -format, -test or -config, or that exits non-zero."""
    assert_golden(transcript(run(["survey", "-h"]), workdir), __file__, "help")


def test_markdown_over_a_module(run, workdir):
    """CATCHES: a survey whose Markdown misses a config chain or a baseline row, counts a finding under the wrong
    column (found, ignored, baselined, reported), prints 0 instead of - for a rule not asked, marks packages read as
    empty or all core wrongly, or orders the package rows by something other than what is outstanding."""
    assert_golden(survey(run, workdir, RICH), __file__, "markdown")


def test_json_over_a_module(run, workdir):
    """CATCHES: a JSON survey that drops the asked flags, the per-package counts, the largest crossing or the checks
    in force, or that differs in shape from the documented arrays."""
    assert_golden(survey(run, workdir, RICH, "-format=json"), __file__, "json")


def test_without_tests(run, workdir):
    """CATCHES: -test=false that still reads test files, so a use only a test makes still counts; and a package of
    test files alone that vanishes without a warning."""
    files = {
        "go.mod": gomod("example.com/m"),
        "p/user.go": "package p\n\nfunc helper() int { return 1 }\n",
        "p/order_test.go": 'package p\n\nimport "testing"\n\nfunc TestOrder(t *testing.T) { _ = helper() }\n',
        "onlytests/x_test.go": 'package onlytests\n\nimport "testing"\n\nfunc TestX(t *testing.T) {}\n',
    }
    write_files(workdir, files)
    with_tests = transcript(run(["survey", "./..."]), workdir)
    without = transcript(run(["survey", "-test=false", "./..."]), workdir)
    assert_golden(with_tests + "\n=== -test=false\n" + without, __file__, "test_false")


def test_explicit_config_replaces_the_chain(run, workdir):
    """CATCHES: survey -config that still reads the discovered .declscope.yaml files, or does not name the explicit
    file in the checks."""
    files = {**RICH, "strict.yaml": "rules:\n  naming:\n    qualify: always\n  surplus: loose\n  unused: loose\n"}
    assert_golden(survey(run, workdir, files, "-config", "strict.yaml", "./app"), __file__, "explicit_config")


def test_refuses_a_package_that_does_not_compile(run, workdir):
    """CATCHES: a survey that counts a package that does not type-check as clean, or that does not name it, its
    error, and a package failing only through the dependency it imports."""
    files = {
        "go.mod": gomod("example.com/m"),
        "bad/bad.go": 'package bad\n\nfunc F() int { return "x" }\n',
        "user/user.go": 'package user\n\nimport "example.com/m/bad"\n\nvar X = bad.F()\n',
        "ok/ok.go": "package ok\n\nfunc a() {}\n",
    }
    assert_golden(survey(run, workdir, files), __file__, "type_error")


def test_allow_errors_measures_the_rest(run, workdir):
    """CATCHES: -allow-errors that measures a failed package as a clean row, or does not list each failed package with
    its first error under the checks."""
    files = {
        "go.mod": gomod("example.com/m"),
        "bad/bad.go": 'package bad\n\nfunc F() int { return "x" }\n',
        "user/user.go": 'package user\n\nimport "example.com/m/bad"\n\nvar X = bad.F()\n',
        "ok/ok.go": "package ok\n\nfunc a() {}\n",
    }
    write_files(workdir, files)
    md = transcript(run(["survey", "-allow-errors"]), workdir)
    js = transcript(run(["survey", "-allow-errors", "-format", "json"]), workdir)
    assert_golden(md + "\n=== json\n" + js, __file__, "allow_errors")


def test_unknown_format(run, workdir):
    """CATCHES: a -format value nobody renders accepted (or rendered as markdown) instead of refused naming what is
    accepted."""
    assert_golden(survey(run, workdir, {"go.mod": gomod("example.com/m"), "p/p.go": "package p\n"}, "-format=yaml"),
                  __file__, "unknown_format")


def test_broken_config(run, workdir):
    """CATCHES: a config that one package cannot load reported as a clean row instead of stopping the survey."""
    files = {"go.mod": gomod("example.com/m"), "p/p.go": "package p\n", "p/.declscope.yaml": "defaults:\n  exported: shared\n"}
    assert_golden(survey(run, workdir, files), __file__, "broken_config")


def test_patterns_matching_nothing(run, workdir):
    """CATCHES: a survey whose only pattern names nothing answered with an empty report, or one beside a matching
    pattern that is not warned about."""
    files = {"go.mod": gomod("example.com/m"), "p/p.go": "package p\n", "empty/README": "x\n"}
    write_files(workdir, files)
    warned = transcript(run(["survey", "./empty/...", "./p"]), workdir)
    refused = transcript(run(["survey", "./empty/..."]), workdir)
    assert_golden(warned + "\n=== only ./empty/...\n" + refused, __file__, "unmatched")


def test_surplus_stands_down_where_the_analyzer_does(run, workdir):
    """CATCHES: a survey that counts surplus findings for a package holding a generated file, which the analyzer
    itself refuses to judge, instead of printing - for the rule there."""
    files = {
        "go.mod": gomod("example.com/m"),
        "p/user.go": "package p\n\n//declscope:shared\nfunc userShared() {}\n",
        "p/gen.go": "// Code generated by hand. DO NOT EDIT.\n\npackage p\n\nvar _ = 1\n",
        "q/user.go": "package q\n\n//declscope:shared\nfunc userShared() {}\n",
    }
    assert_golden(survey(run, workdir, files), __file__, "surplus_stood_down")


def test_counts_what_ignores_answer_and_baselines(run, workdir):
    """CATCHES: findings an ignore silences or a baseline absorbs counted as reported, or not counted at all."""
    files = {
        "go.mod": gomod("example.com/m"),
        ".declscope.yaml": STRICT,
        "p/user.go": "package p\n\n//declscope:ignore boundary\nfunc helper() int { return 1 }\n\nfunc other() int { return 2 }\n",
        "p/order.go": "package p\n\nfunc orderRun() int { return helper() + other() }\n\nvar _ = orderRun\n",
        ".declscope-baseline.yaml": "packages:\n  example.com/m/p:\n    qualify:\n      user:\n        - other\n",
    }
    assert_golden(survey(run, workdir, files, "-format=json"), __file__, "ignored_and_baselined")


def test_dependency_failing_inside_a_function_body(run, workdir):
    """CATCHES: a package whose dependency fails only inside a function body (an error the go command's build output
    alone carries, relative to the working directory) counted as clean, or named without the dependency's position
    made absolute."""
    files = {
        "go.mod": gomod("example.com/m"),
        "b/b.go": 'package b\n\nfunc F() int {\n\treturn "x"\n}\n',
        "a/a.go": 'package a\n\nimport "example.com/m/b"\n\nvar X = b.F\n',
    }
    write_files(workdir, files)
    refused = transcript(run(["survey", "./a"]), workdir)
    allowed = transcript(run(["survey", "-allow-errors", "-format=json", "./a"]), workdir)
    inspected = transcript(run(["inspect", "./a"]), workdir)
    assert_golden(refused + "\n=== -allow-errors\n" + allowed + "\n=== inspect\n" + inspected, __file__, "dependency_body")


def test_counts_directive_problems_and_the_filter_report(run, workdir):
    """CATCHES: a survey that does not count directive problems (found, and ignored by a file-level ignore of
    directive) or the filter rule's report on a package its config chain reads as empty."""
    files = {
        "go.mod": gomod("example.com/m"),
        "p/a.go": "package p\n\n//declscope:bogus\nfunc a() {}\n",
        "p/b.go": "//declscope:ignore directive\n\npackage p\n\n// declscope:shared\nfunc b() {}\n",
        ".declscope.yaml": "filter:\n  only: [\"p/**\", \"q/other.go\"]\n",
        "q/.declscope.yaml": "filter:\n  only: [q.go]\n",
        "q/q.go": "package q\n",
        "q/other.go": "package q\n",
    }
    assert_golden(survey(run, workdir, files, "-format=json"), __file__, "directive_and_filter_counts")
