def test_qualify_rows_per_namespace(run, workdir):
    """CATCHES: a qualify section that prints counts for the core or for a namespace with no target (it must print
    -), or whose saturation is not reported of targets."""
    files = {
        "go.mod": gomod("example.com/m"),
        ".declscope.yaml": "rules:\n  naming:\n    qualify: always\n",
        "user.go": "package p\n\nfunc helper() {}\n\nfunc userOK() {}\n\n//declscope:ignore qualify\nfunc excused() {}\n",
        "empty.go": "package p\n\ntype emptyT = int\n",
        "core.go": "//declscope:core\n\npackage p\n\nfunc open() {}\n",
        "order.go": "package p\n\nvar _ = []any{helper, userOK, excused, open}\n",
    }
    assert_golden(inspect(run, workdir, files, "."), __file__, "qualify_rows")
