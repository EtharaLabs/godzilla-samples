"""One module seen through every command: the analyzer, -json, survey, inspect and baseline must agree.

p reaches helper and userPoint's fields by name and by an unkeyed literal, and a generated file names helper
from a file the analysis does not read. q pairs model's fields by a conversion, which keeps their directives,
and converts ledger only to itself, which does not.
"""

from conftest import GO_MOD, read_golden, write_tree


def golden(name):
    return read_golden(__file__, name)


MODULE = {
    "go.mod": GO_MOD,
    ".declscope.yaml": "rules:\n  naming:\n    qualify: ondemand\n",
    "p/user.go": "package p\n\nfunc helper() int { return 1 }\n\ntype userPoint struct{ x, y int }\n\ntype userA struct {\n"
                 "\t//declscope:shared\n\tn int\n\t//declscope:shared\n\tm int\n}\n",
    "p/order.go": "package p\n\ntype orderB struct {\n\tn int\n\tm int\n}\n\nfunc orderConv(a userA) orderB { return orderB(a) }\n\n"
                  "func orderRun() int {\n\tp := userPoint{1, 2}\n\treturn helper() + p.x\n}\n\nvar _ = orderConv\nvar _ = orderRun\n",
    "p/gen.go": "// Code generated by hand. DO NOT EDIT.\n\npackage p\n\nfunc genUse() int { return helper() }\n\nvar _ = genUse\n",
    "q/model.go": "package q\n\ntype model struct {\n\tID int\n\t//declscope:shared\n\trev int\n\t//declscope:shared\n\tseq int\n}\n\n"
                  "//declscope:shared\nfunc modelNew() model { return model{ID: 1, rev: 2, seq: 3} }\n\ntype ledger struct {\n"
                  "\t//declscope:shared\n\tn int\n}\n\n//declscope:shared\nfunc ledgerNew() ledger { return ledger{n: 1} }\n",
    "q/snapshot.go": "package q\n\ntype snapshot struct {\n\tID  int\n\trev int\n\tseq int\n}\n\n"
                     "func snapshotOf() snapshot { return snapshot(modelNew()) }\n\nvar _ = snapshotOf\n\n"
                     "func snapshotLedger() ledger { return ledger(ledgerNew()) }\n\nvar _ = snapshotLedger\n",
}


def test_analyzer_text(ds, workdir):
    """CATCHES: an analyzer that counts a use from a generated file, misses an unkeyed literal's fields, or
    reports a field whose directive a struct conversion holds together."""
    write_tree(workdir, MODULE)
    out = ds(["./..."])
    assert out.transcript == golden("analyzer")


def test_analyzer_json_withholds_rename_named_by_generated_file(ds, workdir):
    """CATCHES: a -json that offers a rename for helper, which a generated file names and the fix would not
    rewrite, or that differs in any fix it does offer."""
    write_tree(workdir, MODULE)
    out = ds(["-json", "./p"])
    assert out.transcript == golden("analyzer_p_json")


def test_survey_json(ds, workdir):
    """CATCHES: a survey whose counts disagree with what the analyzer reports for the same module."""
    write_tree(workdir, MODULE)
    out = ds(["survey", "-format=json", "./..."])
    assert out.transcript == golden("survey")


def test_inspect_both_packages(ds, workdir):
    """CATCHES: an inspect whose namespaces, crossings, edges or names disagree with the analyzer for either
    package, in markdown or JSON."""
    write_tree(workdir, MODULE)
    outs = [ds(["inspect", "-format=json", "./p"]).transcript, ds(["inspect", "-format=json", "./q"]).transcript,
            ds(["inspect", "./p"]).transcript, ds(["inspect", "./q"]).transcript]
    assert "\n".join(outs) == golden("inspect")


def test_baseline_records_what_the_analyzer_reports(ds, workdir):
    """CATCHES: a baseline that records a different set of keys than the analyzer reports, or leaves the
    analyzer reporting afterwards."""
    write_tree(workdir, MODULE)
    rec = ds(["baseline", "-shrink=false", "-o", "baseline.yaml", "./..."])
    written = (workdir / "baseline.yaml").read_text()
    after = ds(["-config", ".declscope.yaml", "./..."])
    write_tree(workdir, {".declscope.yaml": MODULE[".declscope.yaml"] + "baseline: baseline.yaml\n"})
    quiet = ds(["./..."])
    assert "\n".join([rec.transcript, written, after.transcript, quiet.transcript]) == golden("baseline")
