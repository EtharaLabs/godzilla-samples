"""`pyfun compile --target 3.11` on generated multi-feature programs with f-string reports: the exact Python.

Programs are generated by a seeded composition generator (lane pfcomp, family `fmt`): each one combines
several documented language features in one realistic 20-90 line program, so a single mis-lowered or
mis-checked feature changes the whole transcript. Case data lives in
test_resources/test_hard_composite_fmt_compile311/cases.json; expected transcripts (exit code, stdout, stderr) were captured
from the reference binary under the same environment and working-directory layout as this test.
"""

import json

import pytest

from conftest import case_transcript, golden_name, read_golden, resources_for, run_case

CASES = json.loads((resources_for(__file__) / "cases.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_composite_compile_311_emits_exact_python(run, workdir, case):
    """CATCHES: a 3.11 target that keeps PEP 701 f-strings (string literals inside holes) or rewrites them to a different `.format` call, plus every multi-feature lowering difference of a plain compile."""
    proc, _ = run_case(run, workdir, case)
    assert case_transcript(proc, case, workdir) == read_golden(__file__, golden_name(case["id"]))
