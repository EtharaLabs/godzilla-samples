"""`pyfun compile --native` on generated multi-feature programs: the exact annotated Python.

Programs are generated by a seeded composition generator (lane pfcomp, family `scope`): each one combines
several documented language features in one realistic 20-90 line program, so a single mis-lowered or
mis-checked feature changes the whole transcript. Case data lives in
test_resources/test_hard_composite_scope_native/cases.json; expected transcripts (exit code, stdout, stderr) were captured
from the reference binary under the same environment and working-directory layout as this test.
"""

import json

import pytest

from conftest import case_transcript, golden_name, read_golden, resources_for, run_case

CASES = json.loads((resources_for(__file__) / "cases.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_composite_native_compile_emits_exact_python(run, workdir, case):
    """CATCHES: a `--native` lowering that annotates a top-level binding or function with a different type than the reference infers (units, polymorphism, effects, records, ADTs, Option/Result, tuples, Seq), or lowers one of the program's matches to a different isinstance ladder."""
    proc, _ = run_case(run, workdir, case)
    assert case_transcript(proc, case, workdir) == read_golden(__file__, golden_name(case["id"]))
