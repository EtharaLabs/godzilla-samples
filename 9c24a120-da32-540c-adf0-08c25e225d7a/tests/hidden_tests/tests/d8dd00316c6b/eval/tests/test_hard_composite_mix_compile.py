"""`pyfun compile` on generated multi-feature programs: the exact Python emitted.

Programs are generated by a seeded composition generator (lane pfcomp, family `mix`): each one combines
several documented language features in one realistic 20-90 line program, so a single mis-lowered or
mis-checked feature changes the whole transcript. Case data lives in
test_resources/test_hard_composite_mix_compile/cases.json; expected transcripts (exit code, stdout, stderr) were captured
from the reference binary under the same environment and working-directory layout as this test.
"""

import json

import pytest

from conftest import case_transcript, golden_name, read_golden, resources_for, run_case

CASES = json.loads((resources_for(__file__) / "cases.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_composite_compile_emits_exact_python(run, workdir, case):
    """CATCHES: lowering that differs anywhere in a larger program: helper set and order, imports, temp and capture naming across several functions, dataclass and ordering codegen, match layout, tail-call loops, global/nonlocal for mutation, CE desugaring, units erasure."""
    proc, _ = run_case(run, workdir, case)
    assert case_transcript(proc, case, workdir) == read_golden(__file__, golden_name(case["id"]))
