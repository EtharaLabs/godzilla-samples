// `pyfun bundle`: a static web page that runs the compiled program on
// Pyodide. The page and its loader are fixed text around the program's
// file list, assets, entry module, title and page fragment.

use std::path::Path;

/// The loader, split around the file list, the asset list and the entry.
const LOADER_HEAD: &str = r##"// The bundle's loader (`pyfun bundle`, `DESIGN.md` §6 "Browser target"): boots
// Pyodide from its CDN, stages the compiled Python files and any assets into the
// in-browser file system, and runs the entry module. The page's DOM is reachable
// from the program through Pyodide's `js` module (`extern import js`), stdout and
// stderr land in the two `<pre>` elements, and a raised exception prints there
// too. A module script, so top-level `await` is available.
import { loadPyodide } from "https://cdn.jsdelivr.net/pyodide/v314.0.3/full/pyodide.mjs";

const FILES = "##;
const LOADER_FILES_ASSETS: &str = r##";
const ASSETS = "##;
const LOADER_ASSETS_ENTRY: &str = r##";
const ENTRY = "##;
const LOADER_TAIL: &str = r##";

const stdout = document.getElementById("pyfun-stdout");
const stderr = document.getElementById("pyfun-stderr");
const status = document.getElementById("pyfun-status");
const append = (el, text) => {
  el.textContent += text;
};

status.textContent = "loading Python…";
const pyodide = await loadPyodide({
  indexURL: "https://cdn.jsdelivr.net/pyodide/v314.0.3/full/",
  stdout: (line) => append(stdout, line + "\n"),
  stderr: (line) => append(stderr, line + "\n"),
});

// The compiled modules import each other as siblings (`import geometry`), so
// they are staged in the working directory, which is first on `sys.path`.
for (const name of FILES) {
  const source = await (await fetch(new URL(name, import.meta.url))).text();
  pyodide.FS.writeFile(name, source);
}
for (const name of ASSETS) {
  const bytes = new Uint8Array(await (await fetch(new URL(name, import.meta.url))).arrayBuffer());
  pyodide.FS.writeFile(name, bytes);
}
pyodide.runPython("import sys\nif '' not in sys.path: sys.path.insert(0, '')");

status.textContent = "";
try {
  const entry = pyodide.FS.readFile(ENTRY, { encoding: "utf8" });
  await pyodide.runPythonAsync(entry);
} catch (e) {
  append(stderr, String((e && e.message) || e) + "\n");
}
"##;

/// The page, split around the title and the fragment.
const PAGE_HEAD: &str = r##"<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>"##;
const PAGE_TITLE_BODY: &str = r##"</title>
  <style>
    body { font: 15px/1.5 system-ui, sans-serif; margin: 2rem auto; max-width: 48rem; padding: 0 1rem; }
    pre { white-space: pre-wrap; word-break: break-word; }
    #pyfun-stderr { color: #b00020; }
    #pyfun-status { color: #666; font-style: italic; }
  </style>
</head>
<body>
"##;
const PAGE_TAIL: &str = r##"
  <p id="pyfun-status"></p>
  <pre id="pyfun-stdout"></pre>
  <pre id="pyfun-stderr"></pre>
  <!-- Generated by `pyfun bundle`: the program runs on Pyodide (CPython in
       WebAssembly), loaded from its CDN on first visit; see pyfun-bundle.js. -->
  <script type="module" src="./pyfun-bundle.js"></script>
</body>
</html>
"##;

struct BundleArgs {
    file: String,
    out: String,
    assets: Vec<String>,
    page: Option<String>,
}

fn parse_args(args: &[String]) -> BundleArgs {
    let mut file: Option<String> = None;
    let mut out: Option<String> = None;
    let mut assets = Vec::new();
    let mut page = None;
    let mut i = 0;
    while i < args.len() {
        let a = args[i].as_str();
        let value = |what: &str| -> String {
            match args.get(i + 1) {
                Some(v) => v.clone(),
                None => crate::fail(&format!("error: `{}` needs {}", a, what)),
            }
        };
        match a {
            "-o" => {
                out = Some(value("a directory"));
                i += 2;
            }
            "--asset" => {
                assets.push(value("a file path"));
                i += 2;
            }
            "--page" => {
                page = Some(value("an HTML file"));
                i += 2;
            }
            _ => {
                if file.is_some() {
                    crate::fail(&format!("error: unexpected argument `{}`", a));
                }
                file = Some(a.to_string());
                i += 1;
            }
        }
    }
    let Some(file) = file else { crate::fail("error: `bundle` needs a file path") };
    let Some(out) = out else { crate::fail("error: `bundle` needs `-o <dir>` (the page's directory)") };
    BundleArgs { file, out, assets, page }
}

/// A JavaScript array of strings.
fn js_list(items: &[String]) -> String {
    let quoted: Vec<String> = items.iter().map(|s| js_string(s)).collect();
    format!("[{}]", quoted.join(", "))
}

fn js_string(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

fn plural(n: usize, one: &str) -> String {
    if n == 1 {
        format!("1 {}", one)
    } else {
        format!("{} {}s", n, one)
    }
}

pub fn cmd_bundle(args: &[String]) {
    let a = parse_args(args);
    let ck = crate::load_checked(&a.file, true);
    let em = crate::project::emit_all(&ck, &crate::project::EmitOpts { py311: false, native: false });
    let project = ck.mods.len() > 1;
    // one module runs as `main.py`; a project keeps its module files
    let files: Vec<(String, String)> = if project { em.files.clone() } else { vec![("main.py".to_string(), em.files[0].1.clone())] };
    let entry = if project { format!("{}.py", crate::project::py_module_of(&ck.mods.last().unwrap().file)) } else { "main.py".to_string() };
    let out = Path::new(&a.out);
    if let Err(e) = std::fs::create_dir_all(out) {
        crate::fail(&format!("error: cannot create {}: {}", a.out, e));
    }
    for (f, text) in &files {
        let p = out.join(f);
        if let Err(e) = std::fs::write(&p, text) {
            crate::fail(&format!("error: cannot write {}: {}", p.display(), e));
        }
    }
    let mut asset_names = Vec::new();
    for asset in &a.assets {
        let name = Path::new(asset).file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_else(|| asset.clone());
        if let Err(e) = std::fs::copy(asset, out.join(&name)) {
            crate::fail(&format!("error: cannot copy {}: {}", asset, e));
        }
        asset_names.push(name);
    }
    let fragment = match &a.page {
        Some(p) => match std::fs::read_to_string(p) {
            Ok(s) => s,
            Err(e) => crate::fail(&format!("error: cannot read {}: {}", p, e)),
        },
        None => String::new(),
    };
    let title = Path::new(&a.file).file_stem().map(|s| s.to_string_lossy().to_string()).unwrap_or_default();
    let page = format!("{}{}{}{}{}", PAGE_HEAD, html_escape(&title), PAGE_TITLE_BODY, fragment, PAGE_TAIL);
    let names: Vec<String> = files.iter().map(|(f, _)| f.clone()).collect();
    let loader = format!(
        "{}{}{}{}{}{}{}",
        LOADER_HEAD,
        js_list(&names),
        LOADER_FILES_ASSETS,
        js_list(&asset_names),
        LOADER_ASSETS_ENTRY,
        js_string(&entry),
        LOADER_TAIL
    );
    for (f, text) in [("index.html", &page), ("pyfun-bundle.js", &loader)] {
        let p = out.join(f);
        if let Err(e) = std::fs::write(&p, text) {
            crate::fail(&format!("error: cannot write {}: {}", p.display(), e));
        }
    }
    eprintln!(
        "wrote index.html to {} ({}, {}); serve the directory over http and open it",
        a.out,
        plural(files.len(), "module"),
        plural(asset_names.len(), "asset")
    );
}

// ---- `pyfun build --native`: a C extension through mypyc --------------

const MYPYC_FLAGS: &[&str] = &[
    "--allow-redefinition-new",
    "--local-partial-types",
    "--disable-error-code",
    "func-returns-value",
    "--disable-error-code",
    "var-annotated",
    "--disable-error-code",
    "union-attr",
];

/// A single program's module name: its lowercased stem, or a `_pf_` name
/// when that is not a plain identifier.
fn single_module_name(file: &str) -> String {
    let stem = Path::new(file).file_stem().map(|s| s.to_string_lossy().to_lowercase()).unwrap_or_default();
    let plain = !stem.is_empty() && stem.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_') && !stem.starts_with(|c: char| c.is_ascii_digit());
    if plain {
        stem
    } else {
        let s: String = stem.chars().map(|c| if c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' { c } else { '_' }).collect();
        format!("_pf_{}", s)
    }
}

pub fn cmd_build(args: &[String]) {
    let mut native = false;
    let mut file: Option<String> = None;
    let mut out: Option<String> = None;
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--native" => native = true,
            "-o" => {
                if let Some(v) = args.get(i + 1) {
                    out = Some(v.clone());
                    i += 1;
                }
            }
            a => {
                if file.is_some() {
                    crate::fail(&format!("error: unexpected argument `{}`", a));
                }
                file = Some(a.to_string());
            }
        }
        i += 1;
    }
    if !native {
        crate::fail("error: `build` compiles with mypyc and needs `--native` (pyfun build --native <file> -o <dir>)");
    }
    let Some(file) = file else { crate::fail("error: `build` needs a file path") };
    let Some(out) = out else { crate::fail("error: `build` needs an output directory (-o <dir>)") };
    let ck = crate::load_checked(&file, true);
    let em = crate::project::emit_all(&ck, &crate::project::EmitOpts { py311: false, native: true });
    let project = ck.mods.len() > 1;
    let (files, modules, entry): (Vec<(String, String)>, Vec<String>, String) = if project {
        let modules: Vec<String> = em.files.iter().map(|(f, _)| f.clone()).filter(|f| f != "_pyfun_rt.py").collect();
        let entry = crate::project::py_module_of(&ck.mods.last().unwrap().file);
        (em.files.clone(), modules, entry)
    } else {
        let name = single_module_name(&file);
        let f = format!("{}.py", name);
        (vec![(f.clone(), em.files[0].1.clone())], vec![f], name)
    };
    let dir = Path::new(&out);
    if let Err(e) = std::fs::create_dir_all(dir) {
        crate::fail(&format!("error: cannot create {}: {}", out, e));
    }
    for (f, text) in &files {
        let p = dir.join(f);
        if let Err(e) = std::fs::write(&p, text) {
            crate::fail(&format!("error: cannot write {}: {}", p.display(), e));
        }
    }
    let python = crate::pkg::package_python();
    let status = std::process::Command::new(&python).arg("-m").arg("mypyc").args(MYPYC_FLAGS).args(&modules).current_dir(dir).status();
    match status {
        Ok(s) if s.success() => {}
        Ok(_) => crate::fail("error: mypyc could not build the program (see its output above); it needs `pip install mypy setuptools` and a C compiler"),
        Err(e) => crate::fail(&format!("error: cannot run {}: {}", python, e)),
    }
    // the extension modules replace the Python sources
    for m in &modules {
        let _ = std::fs::remove_file(dir.join(m));
    }
    let main = format!("# Runs the mypyc-compiled Pyfun program `{}`.\nimport {}  # noqa: F401\n", entry, entry);
    if let Err(e) = std::fs::write(dir.join("__main__.py"), main) {
        crate::fail(&format!("error: cannot write {}: {}", dir.join("__main__.py").display(), e));
    }
    println!("built {} natively: run it with `python {}`", file, out);
}
